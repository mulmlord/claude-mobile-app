# ---- keeping the laptop awake ------------------------------------------------------------
def sess(status, since, writer=True):
    return SimpleNamespace(status=status, status_since=since, writer=object() if writer else None)


async def test_awake_holds_while_working_and_for_the_grace_period(inhibitor, clock):
    a = Awake({"keep_awake": "working", "keep_awake_grace_seconds": 180})
    assert await a.update([]) is False and not a.active
    working = [sess("working", clock.now)]
    assert await a.update(working) is True and a.active
    (p,) = inhibitor.procs
    assert "--what=handle-lid-switch:idle" in p.argv and p.argv[-2:] == ["sleep", "infinity"]
    assert await a.update(working) is False  # still held, nothing new
    idle = [sess("idle", clock.now)]
    clock.advance(179)
    assert await a.update(idle) is False and a.active
    clock.advance(2)
    assert await a.update(idle) is True and not a.active
    assert inhibitor.signals == [(p.pid, signal.SIGTERM)]
    assert len(inhibitor.procs) == 1


async def test_awake_while_waiting_for_you_up_to_the_cap(inhibitor, clock):
    a = Awake({"keep_awake_waiting_minutes": 10, "keep_awake_grace_seconds": 1})
    waiting = [sess("permission", clock.now)]
    assert await a.update(waiting) is True
    clock.advance(9 * 60)
    assert await a.update(waiting) is False and a.active
    clock.advance(2 * 60)  # nobody answered for 11 minutes
    assert await a.update(waiting) is True and not a.active
    assert a.wants([sess("question", clock.now)]) is True


