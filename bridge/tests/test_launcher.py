async def test_stuck_inhibitor_gets_sigkill(inhibitor, clock):
    a = Awake({"keep_awake_grace_seconds": 1})
    inhibitor.hang = True
    await a.update([sess("working", clock.now)])
    clock.advance(2)
    assert await a.update([]) is True and not a.active
    pid = inhibitor.procs[0].pid
    assert inhibitor.signals == [(pid, signal.SIGTERM), (pid, signal.SIGKILL)]


