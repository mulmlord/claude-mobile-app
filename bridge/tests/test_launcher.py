class _Spawned:
    def __init__(self, argv, kw):
        self.argv, self.kw = argv, kw
        self.returncode = 0
        self.stderr = asyncio.StreamReader()
        self.stderr.feed_eof()

    async def wait(self):
        return 0


@pytest.fixture
def spawn_env(monkeypatch, bindir):
    st = SimpleNamespace(env={"WAYLAND_DISPLAY": "wayland-1", "PATH": bindir("foot")}, calls=[], wrap="/w/claude-mobile-wrap")
    monkeypatch.setattr(launcher, "desktop_env", lambda: dict(st.env))
    monkeypatch.setattr(launcher, "wrapper_path", lambda: st.wrap)

    async def fake_exec(*argv, **kw):
        p = _Spawned(argv, kw)
        st.calls.append(p)
        return p
    monkeypatch.setattr(asyncio, "create_subprocess_exec", fake_exec)
    return st


