def test_scan_is_cached_by_mtime_and_size(sandbox):
    p = sandbox.home / "p"
    p.mkdir()
    path = make_session(sandbox, p, SID[0], meta("custom-title", customTitle="AAAA"), prompt("x"))
    h = History()
    assert h.find(SID[0])["title"] == "AAAA"
    st = os.stat(path)
    path.write_text(path.read_text().replace("AAAA", "BBBB"))  # same size
    os.utime(path, ns=(st.st_atime_ns, st.st_mtime_ns))
    assert h.find(SID[0])["title"] == "AAAA"  # served from the cache
    os.utime(path, (st.st_atime, st.st_mtime + 5))
    assert h.find(SID[0])["title"] == "BBBB"
    assert h.find(SID[5]) is None


def test_big_files_read_head_and_tail_only(sandbox, monkeypatch):
    monkeypatch.setattr(launcher, "HEAD", 2000)
    monkeypatch.setattr(launcher, "TAIL", 1000)
    p = sandbox.home / "p"
    p.mkdir()

    def entries(c):
        filler = [c.assistant(c.text("filler " * 20)) for _ in range(40)]
        return ([c.prompt("first prompt")] + filler[:20] + [c.meta("ai-title", aiTitle="in the middle")]
                + filler[20:] + [c.meta("ai-title", aiTitle="at the end")])
    path = make_session(sandbox, p, SID[0], entries)
    assert os.path.getsize(path) > 3000
    info = History().find(SID[0])
    assert info["cwd"] == str(p) and info["title"] == "at the end"


