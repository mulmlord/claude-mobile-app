def make_session(sandbox, cwd, sid, *entries_fn, age=0.0, project=None):
    """A transcript in ~/.claude/projects/<project>/<sid>.jsonl; entries_fn(conv) -> entries."""
    d = sandbox.projects / (project or str(cwd).replace("/", "-"))
    d.mkdir(exist_ok=True)
    path = d / f"{sid}.jsonl"
    c = Conv(path, cwd=str(cwd), session_id=sid)
    entries = []
    for fn in entries_fn:
        entries += fn(c)
    c.write(*entries)
    if age:
        touch_old(str(path), age)
    return path


def prompt(text):
    return lambda c: [c.prompt(text)]


def meta(type_, **kw):
    return lambda c: [c.meta(type_, **kw)]


DEFAULT_TMP_PREFIX = launcher.TMP_PREFIX  # read before the sandbox fixture swaps it
