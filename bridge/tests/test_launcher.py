def test_projects_grouped_by_folder_newest_first(sandbox):
    a, b = sandbox.home / "Projects" / "alpha", sandbox.home / "beta"
    a.mkdir(parents=True)
    b.mkdir()
    make_session(sandbox, a, SID[0], prompt("old alpha work"), age=3000)
    make_session(sandbox, a, SID[1], prompt("new alpha work"), age=100)
    make_session(sandbox, b, SID[2], prompt("beta work"), age=1000)
    out = History().projects(live={SID[1]: "w7"}, running={SID[1], SID[2]})
    assert [p["name"] for p in out] == ["alpha", "beta"]
    alpha = out[0]
    assert alpha["cwd"] == str(a) and alpha["path"] == "~/Projects/alpha"
    assert [s["session_id"] for s in alpha["sessions"]] == [SID[1], SID[0]]
    assert alpha["updated"] == alpha["sessions"][0]["updated"]
    assert alpha["sessions"][0]["live"] == "w7" and alpha["sessions"][0]["running"] is True
    assert alpha["sessions"][1]["live"] is None and alpha["sessions"][1]["running"] is False
    assert out[1]["sessions"][0]["title"] == "beta work"


def test_title_priority(sandbox):
    p = sandbox.home / "p"
    p.mkdir()
    make_session(sandbox, p, SID[0], prompt("typed"), meta("ai-title", aiTitle="AI"),
                 meta("summary", summary="Summary"), meta("custom-title", customTitle="Custom"))
    make_session(sandbox, p, SID[1], meta("ai-title", aiTitle="AI"), prompt("typed"),
                 meta("summary", summary="Summary"))
    make_session(sandbox, p, SID[2], prompt("typed"), meta("ai-title", aiTitle="AI"))
    make_session(sandbox, p, SID[3], prompt("typed"))
    h = History()
    titles = {s["session_id"]: s["title"] for s in h.projects({}, set())[0]["sessions"]}
    assert titles == {SID[0]: "Custom", SID[1]: "Summary", SID[2]: "AI", SID[3]: "typed"}


